import os
import subprocess
import requests

def create_pr(issue_key, title_summary):
    try:
        branch_name = subprocess.check_output(
            ["git", "branch", "--show-current"], text=True
        ).strip()
        print(f"📡 Current branch detected: {branch_name}")

        GITHUB_TOKEN = os.getenv("GITHUB_TOKEN")
        REPO_OWNER = os.getenv("GITHUB_OWNER")
        REPO_NAME = os.getenv("GITHUB_REPO")

        if not all([GITHUB_TOKEN, REPO_OWNER, REPO_NAME]):
            print("⚠ Missing GitHub environment variables. Skipping PR creation.")
            return None

        # ⭐ 正确的 GitHub API endpoint
        url = f"https://api.github.com/repos/{REPO_OWNER}/{REPO_NAME}/pulls"

        headers = {
            "Authorization": f"token {GITHUB_TOKEN}",
            "Accept": "application/vnd.github.v3+json",
            "User-Agent": "AquaRAG-Automation-Agent/1.0"
        }

        payload = {
            "title": f"[{issue_key}] {title_summary}",
            "head": branch_name,
            "base": "main",
            "body": (
                f"### JIRA Ticket\nFixes {issue_key}\n\n"
                f"### Summary\nThis PR was automatically generated by the AquaRAG Automation Agent."
            ),
            "draft": False
        }

        print(f"📡 Requesting GitHub API: {url}")
        response = requests.post(url, json=payload, headers=headers)

        if response.status_code == 201:
            pr_url = response.json().get("html_url")
            print(f"✅ Pull Request successfully created: {pr_url}")
            return pr_url
        else:
            print(f"❌ Failed to create PR. Status Code: {response.status_code}")
            print("=" * 50)
            print("🔍 GitHub Response Text Preview:")
            print(response.text[:1000])
            print("=" * 50)
            return None

    except Exception as e:
        print(f"❌ Error during PR workflow: {e}")
        return None
